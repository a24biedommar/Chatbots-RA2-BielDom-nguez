/**
 * Calcula el preu total amb IVA.
 * 
 * Lògica:
 * A. Rep el preu base i el percentatge d'IVA.
 * B. Calcula la quantitat d'IVA.
 * C. Suma l'IVA al preu base.
 * D. Retorna el resultat final.
 */
function calcularPreuTotal(preuBase, percentatgeIva) {
    var quantitatIva = (preuBase * percentatgeIva) / 100;
    var preuFinal = preuBase + quantitatIva;
    
    return preuFinal;
}

